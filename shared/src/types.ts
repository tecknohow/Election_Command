/**
 * Shared data model between the ingestion server and the web client.
 * Everything the UI renders is derived from a `Snapshot` plus incremental `StreamEvent`s.
 */

/** D = Democrat, R = Republican, I = Independent / other (incl. third parties). */
export type Party = 'D' | 'R' | 'I';

/** S = U.S. Senate, G = Governor, H = U.S. House, B = ballot measure (phase 2). */
export type Office = 'S' | 'G' | 'H';

export type RatingLevel = 'solid' | 'likely' | 'lean' | 'tilt' | 'tossup';

export interface Rating {
  /** Forecaster that produced the rating. FLIPR = Silver Bulletin model. */
  source: 'FLIPR' | 'Cook' | 'NYT';
  level: RatingLevel;
  /** Favored party. null for toss-ups. */
  party: Party | null;
  /** Human-readable label, e.g. "Lean R". */
  label: string;
}

export interface Candidate {
  id: string;
  name: string;
  lastName: string;
  party: Party;
  /** Raw party name from the provider ("Democrat", "Libertarian", ...). */
  partyName: string;
  incumbent: boolean;
  votes: number;
  /** Percent of the total vote, 0-100. */
  pct: number;
  winner: boolean;
  img?: string | null;
}

export interface MarketOutcome {
  /** Candidate / outcome label as listed on the market. */
  label: string;
  party: Party | null;
  /** Implied probability 0-1. */
  prob: number;
}

export interface MarketData {
  source: 'Polymarket';
  slug: string;
  url: string;
  outcomes: MarketOutcome[];
  /** Implied probability per party (sum of outcomes for that party). */
  byParty: Partial<Record<Party, number>>;
  volume: number | null;
  updatedAt: string;
}

export type RaceStatus =
  /** Polls still open in the state. */
  | 'upcoming'
  /** Polls closed, no votes reported yet. */
  | 'closed'
  /** Votes are being counted, no call yet. */
  | 'counting'
  /** A winner has been projected. */
  | 'called'
  /** Advances to a runoff (e.g. GA, LA). */
  | 'runoff';

export interface Race {
  /** Stable id: `${state}-${office}` or `${state}-H-${district}`, e.g. TX-S, OH-G, CA-H-12. */
  id: string;
  office: Office;
  state: string;
  district: number | null;
  special: boolean;
  title: string;
  candidates: Candidate[];
  totalVotes: number;
  expectedVotes: number | null;
  /** Estimated expected vote percentage counted, 0-100. */
  eevp: number | null;
  precinctsReporting: number | null;
  precinctsTotal: number | null;
  status: RaceStatus;
  pollClose: string | null;
  /** Party of the projected winner. */
  winner: Party | null;
  winnerName: string | null;
  calledBy: string | null;
  calledAt: string | null;
  /** Party that held the seat before this election. */
  priorParty: Party | null;
  incumbentName: string | null;
  incumbentRunning: boolean;
  /** Current vote leader (null if no votes). */
  leader: Party | null;
  leaderName: string | null;
  /** Leader margin in percentage points. */
  margin: number | null;
  /** True when the projected winner's party differs from the prior holder. */
  flip: boolean;
  uncontested: boolean;
  /** Ranked-choice tabulation (first-choice votes shown; final result may take days). */
  rcv?: boolean;
  /** Majority required, otherwise a runoff (e.g. Georgia). */
  runoffRule?: string | null;
  /** Set when a decision is expected later (RCV tabulation, likely runoff, too close, slow count). */
  expectedLater?: string | null;
  forecast: {
    flipr?: Rating;
    cook?: Rating;
    nyt?: Rating;
  };
  market?: MarketData;
  /** Which provider the vote numbers came from. */
  source: string;
  /** Link to an authoritative results page. */
  url: string | null;
  updatedAt: string | null;
}

export interface PartyCounts {
  D: number;
  R: number;
  I: number;
}

export interface ChamberSummary {
  office: Office;
  label: string;
  total: number;
  /** Seats needed for majority for each side (accounts for VP tiebreak in the Senate). */
  toControl: { D: number; R: number };
  /** Seats not up for election, by holding party. Independents caucusing with D are counted in I. */
  notUp: PartyCounts;
  /** Seats held by each party before the election (all seats). */
  before: PartyCounts;
  won: PartyCounts;
  leading: PartyCounts;
  /** Races up this cycle. */
  racesTotal: number;
  racesCalled: number;
  /** Races with no votes and no call. */
  racesPending: number;
  flips: { toD: number; toR: number; toI: number };
  /** Party that has clinched control, if any. */
  controlWinner: Party | null;
  market?: MarketData;
  /** How independents are treated. */
  note?: string;
}

export type NewsKind = 'news' | 'call' | 'flip' | 'polls' | 'lead' | 'measure' | 'system';

export interface NewsItem {
  id: string;
  kind: NewsKind;
  source: string;
  title: string;
  summary?: string;
  link?: string;
  published: string;
  raceId?: string;
  party?: Party | null;
  /** Generated by the simulator — never mixed with live data. */
  sim?: boolean;
}

export interface SourceStatus {
  id: string;
  name: string;
  /** What this source provides. */
  role: string;
  ok: boolean;
  enabled: boolean;
  lastSuccess: string | null;
  lastAttempt: string | null;
  lastError: string | null;
  intervalMs: number;
  lastDurationMs: number | null;
  /** Number of consecutive failures (drives backoff). */
  failures: number;
  /** Count of 304 Not Modified / unchanged responses. */
  notModified: number;
  requests: number;
  detail?: string;
}

export interface PollClosing {
  state: string;
  time: string;
}

export interface BopHistoryPoint {
  t: string;
  S: { D: number; R: number; I: number };
  H: { D: number; R: number; I: number };
  G: { D: number; R: number; I: number };
}

export interface SimStatus {
  enabled: boolean;
  allowed: boolean;
  running: boolean;
  speed: number;
  simTime: string | null;
}

export type MeasureType = 'constitutional' | 'statute' | 'unknown';

export interface MeasureChoice {
  label: string;
  /** Normalized side: Yes/For = yes, No/Against = no. */
  side: 'yes' | 'no' | 'other';
  votes: number;
  pct: number;
  winner: boolean;
}

export interface BallotMeasure {
  /** `${state}-${number}` for measures with a results feed, `${state}-cat-${n}` for catalog-only. */
  id: string;
  state: string;
  /** Official designation, e.g. "Proposition 5", "Amendment 81". */
  code: string | null;
  /** Short question / title. */
  title: string;
  /** What a "yes" vote does. */
  description: string | null;
  type: MeasureType;
  /** "Legislature" (referred) or "Citizens" (initiative). */
  origin: string | null;
  topics: string[];
  choices: MeasureChoice[];
  totalVotes: number;
  eevp: number | null;
  status: RaceStatus;
  result: 'passed' | 'failed' | null;
  yesPct: number | null;
  /** Share of the vote needed to pass (e.g. 60 in Florida). */
  threshold: number;
  pollClose: string | null;
  /** True when a live results feed covers this measure. */
  live: boolean;
  source: string;
  calledBy: string | null;
  url: string | null;
  /** The measure's Ballotpedia page (https://ballotpedia.org/...), when known. */
  ballotpediaUrl: string | null;
  /** Wikipedia fallback link when there's no Ballotpedia page (the article, or the state's list). */
  wikipediaUrl: string | null;
  updatedAt: string | null;
}

/** One sub-state reporting unit (county; Alaska state-house district; county part of a House district). */
export interface CountyUnit {
  /** Provider id, e.g. "TX-county-48-001". */
  id: string;
  /** 5-digit county FIPS when the unit is a county (matches us-atlas ids), else null. */
  fips: string | null;
  name: string;
  level: string;
  eevp: number | null;
  totalVotes: number;
  expectedVotes: number | null;
  /** Votes per candidate id (ids match Race.candidates[].id). */
  votes: Record<string, number>;
  /** 2024 presidential margin in this unit (D minus R, pct points). */
  baselineMargin: number | null;
}

export interface RaceCounties {
  raceId: string;
  updatedAt: string | null;
  source: string;
  units: CountyUnit[];
}

export type RacePatch = Partial<Race> & { id: string };
export type MeasurePatch = Partial<BallotMeasure> & { id: string };

/** Shallow diff: id plus every top-level field whose value changed. */
export function diffFields<T extends { id: string }>(prev: T | undefined, next: T): (Partial<T> & { id: string }) | null {
  if (!prev) return next;
  const out: Record<string, unknown> = { id: next.id };
  let changed = false;
  for (const k of Object.keys(next) as (keyof T)[]) {
    const a = prev[k];
    const b = next[k];
    if (a === b) continue;
    if (typeof a === 'object' && typeof b === 'object' && JSON.stringify(a) === JSON.stringify(b)) continue;
    out[k as string] = b;
    changed = true;
  }
  // Fields removed in `next` (e.g. a market disappearing) are sent as null.
  for (const k of Object.keys(prev) as (keyof T)[]) {
    if (!(k in next)) {
      out[k as string] = null;
      changed = true;
    }
  }
  return changed ? (out as Partial<T> & { id: string }) : null;
}

export interface Snapshot {
  version: number;
  generatedAt: string;
  mode: 'live' | 'simulation';
  races: Record<string, Race>;
  measures: Record<string, BallotMeasure>;
  chambers: Record<Office, ChamberSummary>;
  news: NewsItem[];
  sources: SourceStatus[];
  pollClosings: PollClosing[];
  bopHistory: BopHistoryPoint[];
  sim: SimStatus;
}

export type StreamEvent =
  | { type: 'snapshot'; data: Snapshot }
  /** Patches: `id` plus only the fields that changed (a full object for races new to the client). */
  | { type: 'races'; version: number; data: RacePatch[] }
  | { type: 'chambers'; version: number; data: Record<Office, ChamberSummary> }
  | { type: 'measures'; version: number; data: MeasurePatch[] }
  | { type: 'news'; version: number; data: NewsItem[] }
  | { type: 'sources'; version: number; data: SourceStatus[] }
  | { type: 'meta'; version: number; data: { mode: Snapshot['mode']; sim: SimStatus; pollClosings: PollClosing[]; bopPoint?: BopHistoryPoint } };
